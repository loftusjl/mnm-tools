const { contextBridge, ipcRenderer } = require('electron');

contextBridge.exposeInMainWorld('mapAPI', {
  loadData: () => ipcRenderer.invoke('load-data'),
  saveData: (data) => ipcRenderer.invoke('save-data', data),
  chooseMapImage: () => ipcRenderer.invoke('choose-map-image'),
  exportData: (scope, zones) => ipcRenderer.invoke('export-data', { scope, zones }),
  importOpen: () => ipcRenderer.invoke('import-open'),
  importCommit: (names) => ipcRenderer.invoke('import-commit', names),
  wikiZoneList: () => ipcRenderer.invoke('wiki-zone-list'),
  wikiFetchMap: (zoneName) => ipcRenderer.invoke('wiki-fetch-map', zoneName),
  wikiListMaps: (zoneName) => ipcRenderer.invoke('wiki-list-maps', zoneName),
  wikiDownloadMap: (zoneName, title) => ipcRenderer.invoke('wiki-download-map', { zoneName, title }),
  onGameZone: (callback) => ipcRenderer.on('game-zone', (event, name) => callback(name)),
  currentGameZone: () => ipcRenderer.invoke('current-game-zone'),
  toggleOverlay: () => ipcRenderer.invoke('toggle-overlay'),
  overlayClickThrough: (on) => ipcRenderer.invoke('overlay-click-through', on),
  overlayFull: (on) => ipcRenderer.invoke('overlay-full', on),
  overlayExit: () => ipcRenderer.invoke('overlay-exit'),
  overlayOpacity: (value) => ipcRenderer.invoke('overlay-opacity', value),
  overlaySetIgnore: (ignore) => ipcRenderer.invoke('overlay-set-ignore', ignore),
  minimizeWindow: () => ipcRenderer.invoke('window-minimize'),
  onOverlayState: (callback) => ipcRenderer.on('overlay-state', (event, state) => callback(state)),
  trackerScan: () => ipcRenderer.invoke('tracker-scan'),
  trackerSetEnabled: (on) => ipcRenderer.invoke('tracker-set-enabled', on),
  publishMnmdb: () => ipcRenderer.invoke('publish-mnmdb'),
  exportContribution: () => ipcRenderer.invoke('export-contribution'),
  zoneAliases: () => ipcRenderer.invoke('zone-aliases'),
  sessionReplay: (opts) => ipcRenderer.invoke('session-replay', opts),
  sessionEnd: () => ipcRenderer.invoke('session-end'),
  lootList: (opts) => ipcRenderer.invoke('loot-list', opts),
  lootVendors: (item) => ipcRenderer.invoke('loot-vendors', item),
  vendorList: (zone) => ipcRenderer.invoke('vendor-list', zone),
  vendorSources: () => ipcRenderer.invoke('vendor-sources'),
  vendorSession: (req) => ipcRenderer.invoke('vendor-session', req),
  itemNames: () => ipcRenderer.invoke('item-names'),
  vendorAdd: (v) => ipcRenderer.invoke('vendor-add', v),
  vendorRename: (r) => ipcRenderer.invoke('vendor-rename', r),
  reportAdd: (r) => ipcRenderer.invoke('report-add', r),
  reportRefuse: (r) => ipcRenderer.invoke('report-refuse', r),
  reportEdit: (r) => ipcRenderer.invoke('report-edit', r),
  reportDelete: (r) => ipcRenderer.invoke('report-delete', r),
  itemOverride: (o) => ipcRenderer.invoke('item-override', o),
  onLootUpdated: (cb) => ipcRenderer.on('loot-updated', () => cb()),
  tradeLog: (rec) => ipcRenderer.invoke('trade-log', rec),
  tradeItemNames: () => ipcRenderer.invoke('trade-item-names'),
  onTrackerUpdated: (cb) => ipcRenderer.on('tracker-updated', (e, s) => cb(s)),
  saveJson: (name, data) => ipcRenderer.invoke('save-json', { name, data }),
  discordLogin: () => ipcRenderer.invoke('discord-login'),
  onDiscordAuth: (cb) => ipcRenderer.on('discord-auth', (e, data) => cb(data)),
});
